//! Tokenizes every hello-world snippet at build time, so syntax highlighting
//! needs no grammar or regex engine in the shipped binary.
//!
//! Writes `$OUT_DIR/highlighted.rs`, which defines:
//!
//! ```ignore
//! pub static HIGHLIGHTED: &[(ProgrammingLanguageDialect, &[(TokenKind, &str)])]
//! ```
//!
//! `TokenKind` is not defined here: the generated code refers to it by name, so
//! it must be in scope wherever the file is `include!`d.

use std::error::Error;
use std::fmt::Write as _;
use std::path::PathBuf;

use hw_pp_core::data::programming_languages::{PROGRAMMING_LANGUAGES, ProgrammingLanguage};
use syntect::easy::ScopeRangeIterator;
use syntect::parsing::{ParseState, ScopeStack, SyntaxReference, SyntaxSet};
use syntect::util::LinesWithEndings;

/// Scope prefixes that win over everything nested inside them, checked in order.
/// This keeps a string's quote marks (`punctuation.definition.string`) part of
/// the `String` token rather than splitting them off as punctuation.
const ENCLOSING: &[(&str, &str)] = &[("comment", "Comment"), ("string", "String")];

/// Scope prefixes matched against the innermost scope first, checked in order.
const INNERMOST: &[(&str, &str)] = &[
    ("constant.numeric", "Number"),
    ("support.macro", "Macro"),
    ("entity.name.macro", "Macro"),
    ("entity.name.function", "Function"),
    ("support.function", "Function"),
    ("variable.function", "Function"),
    // Definition keywords (`fn`, `class`, `struct`) are `storage.type.*` in many
    // grammars; they must win over the plain `storage.type` (`int`, `void`) rule.
    ("storage.type.function", "Keyword"),
    ("storage.type.class", "Keyword"),
    ("storage.type.struct", "Keyword"),
    ("storage.type.enum", "Keyword"),
    ("storage.type.module", "Keyword"),
    ("storage.type", "Type"),
    ("entity.name.type", "Type"),
    ("support.type", "Type"),
    ("keyword", "Keyword"),
    ("storage", "Keyword"),
    ("punctuation", "Punctuation"),
];

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo::rerun-if-changed=build.rs");

    let syntaxes = SyntaxSet::load_defaults_newlines();
    let mut entries = String::new();
    let mut unhighlighted = Vec::new();

    for language in PROGRAMMING_LANGUAGES {
        let Some(syntax) = find_syntax(&syntaxes, language) else {
            unhighlighted.push(language.name.as_str());
            for version in language.versions {
                write_entry(&mut entries, version.label, &[("Plain", version.syntax)])?;
            }
            continue;
        };
        for version in language.versions {
            let tokens = tokenize(&syntaxes, syntax, version.syntax)?;
            write_entry(&mut entries, version.label, &tokens)?;
        }
    }

    let mut generated = String::from("// @generated by build.rs - do not edit.\n");
    writeln!(
        generated,
        "// No bundled grammar (emitted as one Plain token): {}.\n",
        unhighlighted.join(", ")
    )?;
    writeln!(
        generated,
        "pub static HIGHLIGHTED: &[(\
         ::hw_pp_core::data::programming_languages::ProgrammingLanguageDialect, \
         &[(TokenKind, &str)])] = &[\n{entries}];"
    )?;

    let out_dir = PathBuf::from(std::env::var("OUT_DIR")?);
    std::fs::write(out_dir.join("highlighted.rs"), generated)?;
    Ok(())
}

/// Prefers the language name, then its extensions. Name first matters for
/// shared extensions: `m` would otherwise make MATLAB highlight as Objective-C.
fn find_syntax<'a>(
    syntaxes: &'a SyntaxSet,
    language: &ProgrammingLanguage,
) -> Option<&'a SyntaxReference> {
    syntaxes
        .find_syntax_by_name(language.name.as_str())
        .or_else(|| {
            language
                .extensions
                .iter()
                .find_map(|ext| syntaxes.find_syntax_by_extension(ext.as_str()))
        })
}

/// Splits `source` into `(kind, text)` pairs, merging neighbours of the same kind.
fn tokenize<'s>(
    syntaxes: &SyntaxSet,
    syntax: &SyntaxReference,
    source: &'s str,
) -> Result<Vec<(&'static str, &'s str)>, Box<dyn Error>> {
    let mut parser = ParseState::new(syntax);
    let mut stack = ScopeStack::new();
    // (kind, start, end) as byte offsets into `source`.
    let mut spans: Vec<(&'static str, usize, usize)> = Vec::new();
    let mut line_start = 0;

    for line in LinesWithEndings::from(source) {
        let ops = parser.parse_line(line, syntaxes)?;
        for (range, op) in ScopeRangeIterator::new(&ops, line) {
            stack.apply(op)?;
            if range.is_empty() {
                continue;
            }
            let (start, end) = (line_start + range.start, line_start + range.end);
            let kind = classify(&stack);
            match spans.last_mut() {
                // Spans are contiguous, so a same-kind neighbour just grows.
                Some((last_kind, _, last_end)) if *last_kind == kind => *last_end = end,
                _ => spans.push((kind, start, end)),
            }
        }
        line_start += line.len();
    }
    Ok(spans
        .into_iter()
        .map(|(kind, start, end)| (kind, &source[start..end]))
        .collect())
}

fn classify(stack: &ScopeStack) -> &'static str {
    let scopes: Vec<String> = stack.as_slice().iter().map(|s| s.build_string()).collect();
    let matches = |prefix: &str, scope: &str| {
        scope == prefix
            || scope
                .strip_prefix(prefix)
                .is_some_and(|rest| rest.starts_with('.'))
    };

    ENCLOSING
        .iter()
        .find(|(prefix, _)| scopes.iter().any(|scope| matches(prefix, scope)))
        .or_else(|| {
            scopes
                .iter()
                .rev()
                .find_map(|scope| INNERMOST.iter().find(|(prefix, _)| matches(prefix, scope)))
        })
        .map_or("Plain", |(_, kind)| kind)
}

fn write_entry(
    out: &mut String,
    label: impl std::fmt::Debug,
    tokens: &[(&str, &str)],
) -> Result<(), std::fmt::Error> {
    // `Debug` on the dialect gives the variant name (`Rust2021`), and `Debug` on
    // `&str` gives a correctly escaped Rust string literal.
    writeln!(
        out,
        "    (::hw_pp_core::data::programming_languages::ProgrammingLanguageDialect::{label:?}, &["
    )?;
    for (kind, text) in tokens {
        writeln!(out, "        (TokenKind::{kind}, {text:?}),")?;
    }
    writeln!(out, "    ]),")
}
